    using WbcControlTargetSubscription = rclcpp::Subscription<WbcControlTargetMsg>::SharedPtr;

    using TaskStatusMsg = wbc_msgs::msg::TaskStatus; 

    class RbsTaskInterface{
        public:
            wbc::types::RigidBodyState setpoint;
            wbc::types::RigidBodyState feedback;
            wbc::CartesianPosPDController controller;
            wbc::types::SpatialAcceleration ctrl_out;
            wbc::SpatialAccelerationTaskPtr task;
            wbc_msgs::msg::TaskStatus task_status_msg;

            void update(wbc::RobotModelPtr robot_model, const RigidBodyStateMsg& setpoint_msg){
                fromROS(setpoint_msg, setpoint);

                feedback.pose = robot_model->pose(task->tipFrame());
                feedback.twist = robot_model->twist(task->tipFrame());
                feedback.acceleration.setZero();
                    
                ctrl_out = controller.update(setpoint.pose, 
                                                setpoint.twist, 
                                                setpoint.acceleration,
                                                feedback.pose,
                                                feedback.twist);                                           
                task->setReference(ctrl_out);
            }
            const TaskStatusMsg& computeTaskStatus(wbc::RobotModelPtr robot_model, const Eigen::VectorXd& qdd_solver_output,  const Eigen::VectorXd& qdd){
                task_status_msg.y_ref.resize(6);
                task_status_msg.y_solution.resize(6);
                task_status_msg.y.resize(6);

                Eigen::VectorXd y_solution = robot_model->spaceJacobian(task->tipFrame())*qdd_solver_output + robot_model->spatialAccelerationBias(task->tipFrame()).vector6d();
                Eigen::VectorXd y = robot_model->spaceJacobian(task->tipFrame())*qdd + robot_model->spatialAccelerationBias(task->tipFrame()).vector6d();
                
                task_status_msg.y_ref = std::vector<double>(task->y_ref.data(), task->y_ref.data() + task->y_ref.size());
                task_status_msg.y_solution = std::vector<double>(y_solution.data(), y_solution.data() + y_solution.size());
                task_status_msg.y = std::vector<double>(y.data(), y.data() + y.size());

                return task_status_msg;
            }
    };

    class JointPositionTaskInterface{
        public:
            wbc::types::JointCommand setpoint;
            wbc::types::JointState feedback;
            wbc::JointPosPDControllerPtr controller;
            wbc::JointAccelerationTaskPtr task;
            std::vector<int> joint_idx_map;
            Eigen::VectorXd ctrl_out;
            wbc_msgs::msg::TaskStatus task_status_msg;
            
            void update(wbc::RobotModelPtr robot_model, const JointCommandMsg& setpoint_msg, const std::vector<int>& joint_idx_map){
                fromROS(setpoint_msg, joint_idx_map, setpoint);
                feedback.position = robot_model->jointState().position;
                feedback.velocity = robot_model->jointState().velocity;
                ctrl_out = controller->update(setpoint.position, 
                                            setpoint.velocity, 
                                            setpoint.acceleration,
                                            feedback.position,
                                            feedback.velocity);
                task->setReference(ctrl_out);
            }
            const TaskStatusMsg& computeTaskStatus(wbc::RobotModelPtr robot_model, const Eigen::VectorXd& qdd_solver_output,  const Eigen::VectorXd& qdd){
                task_status_msg.y_ref = std::vector<double>(task->y_ref.data(), task->y_ref.data() + task->y_ref.size());
                task_status_msg.y_solution = std::vector<double>(qdd_solver_output.tail(robot_model->na()).data(), qdd_solver_output.tail(robot_model->na()).data() + robot_model->na());
                task_status_msg.y = std::vector<double>(qdd.tail(robot_model->na()).data(), qdd.tail(robot_model->na()).data() + robot_model->na());
                return task_status_msg;
            }
    };

    public:
        BipedController(const std::string& name, const rclcpp::NodeOptions & options = rclcpp::NodeOptions());
        ~BipedController(){};

        virtual CallbackReturn on_configure(const rclcpp_lifecycle::State & previous_state) override;
        virtual CallbackReturn on_activate(const rclcpp_lifecycle::State & previous_state) override;
        virtual CallbackReturn on_deactivate(const rclcpp_lifecycle::State & previous_state) override;
        virtual CallbackReturn on_cleanup(const rclcpp_lifecycle::State & previous_state) override;
        virtual CallbackReturn on_error(const rclcpp_lifecycle::State & previous_state) override;
        virtual CallbackReturn on_shutdown(const rclcpp_lifecycle::State & previous_state) override;

        void updateController();
        void handleContacts(const ContactsMsg& msg);
        void robot_state_callback(const RobotStateMsgPtr msg);
        void set_dynamic_params(whole_body_control::Params params);
        void setpoint_callback(const WbcControlTargetMsgPtr msg);

    protected:
        RbsTaskInterface body_task_iface;
        RbsTaskInterface foot_l_iface;
        RbsTaskInterface foot_r_iface;
        JointPositionTaskInterface joint_pos_iface;

        wbc::ContactWrenchTaskPtr force_l_task;
        wbc::ContactWrenchTaskPtr force_r_task;

        std::shared_ptr<wbc::AccelerationSceneReducedTSID> scene;
        wbc::RobotModelPtr robot_model;
        wbc::QPSolverPtr solver;
        wbc::types::JointState joint_state;
        wbc::types::RigidBodyState floating_base_state;
        wbc::types::Wrench contact_force_l, contact_force_r;
        std::vector<wbc::types::Contact> contacts;
        bool has_robot_state, has_setpoint;
        int update_rate;
